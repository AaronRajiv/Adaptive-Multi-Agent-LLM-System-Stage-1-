"""
Real End-to-End PDF RAG Integration Test against live running backend server.
Uses real Google Gemini API and real FIA 2025 Formula 1 Technical Regulations PDF.
"""

from pathlib import Path
import httpx
import pypdf
import pytest


@pytest.mark.live
def test_real_pdf_rag_end_to_end():
    """Live end-to-end test using the real FIA 2025 Technical Regulations PDF."""
    pdf_path = Path("backend/data/fia_2025_formula_1_technical_regulations.pdf")
    if not pdf_path.exists():
        pdf_path = Path("data/fia_2025_formula_1_technical_regulations.pdf")

    assert pdf_path.exists(), f"Real FIA PDF not found at {pdf_path}"

    reader = pypdf.PdfReader(str(pdf_path))
    # Extract text from key regulatory pages (covering Articles 3, 4, 5)
    extracted_text_parts = []
    # In FIA 2025 tech regs, articles 3, 4, 5 are located across the first 45 pages
    for page_idx in range(min(45, len(reader.pages))):
        text = reader.pages[page_idx].extract_text()
        if any(term in text for term in ["3.4.1", "4.1", "5.1", "Minimum Mass", "Overall Dimensions", "Power Unit"]):
            extracted_text_parts.append(f"--- Page {page_idx + 1} ---\n{text}")

    fia_pdf_text = "\n\n".join(extracted_text_parts)
    if not fia_pdf_text.strip():
        # Fallback to reading first 20 pages
        fia_pdf_text = "\n\n".join(reader.pages[i].extract_text() for i in range(20))

    doc_payload = {
        "filename": "fia_2025_formula_1_technical_regulations.pdf",
        "content": fia_pdf_text,
    }

    request_payload = {
        "task": (
            "Analyze the 2025 FIA Formula 1 technical regulations for car minimum mass (Article 4.1), "
            "overall car dimensions (Article 3.4.1), and fuel mass flow rate limit (Article 5.1). "
            "Cite all specific article numbers and exact numeric limits."
        ),
        "documents": [doc_payload],
    }

    print("\nSending live API request to http://localhost:8000/api/run with real FIA PDF...")
    try:
        response = httpx.post("http://localhost:8000/api/run", json=request_payload, timeout=120.0)
    except httpx.RequestError as e:
        pytest.skip(f"Backend server is not reachable at http://localhost:8000: {e}")

    if response.status_code in (429, 500, 502) and any(
        err_term in response.text.lower() for err_term in ["quota", "429", "rate limit", "resource_exhausted"]
    ):
        pytest.skip(f"Google Gemini live API quota exceeded for live integration test: {response.text}")

    print("HTTP Status Code:", response.status_code)
    assert response.status_code == 200, f"Error: {response.text}"

    data = response.json()
    print("Run ID:", data["run_id"])
    print("\nSubtasks generated by Planner:")
    for t in data["subtasks"]:
        retrieval_q = t.get("metadata", {}).get("retrieval_query") if t.get("metadata") else None
        print(f"  - [{t['id']}] ({t['type']}) {t['description']} | retrieval_query: {retrieval_q}")

    print(f"\nRetrieved Chunks Count: {len(data['retrieved_chunks'])}")
    for i, chunk in enumerate(data["retrieved_chunks"][:3]):
        print(f"\nChunk {i+1} [Doc: {chunk.get('document_id')} | Score: {chunk.get('similarity_score', 0):.2f}]:")
        print("  Content snippet:", chunk.get("content", "")[:120], "...")

    print("\nFinal Answer Snippet:")
    print(data["final_answer"][:400], "...")

    # Assert behavior (non-empty ledger, citations resolve to retrieved chunks, no uncited numbers)
    # 1. Non-empty evidence ledger
    assert data.get("retrieved_chunks") and len(data["retrieved_chunks"]) > 0, "Evidence ledger must not be empty"

    # 2. Citations resolve to retrieved chunks
    eval_data = data.get("evaluation") or {}
    verification = data.get("verification_result") or eval_data.get("verification_result") or {}
    assert verification.get("total_citations", 0) > 0, "Expected citations in final answer"
    cit_validity = verification.get("citation_validity", 0.0)
    assert cit_validity >= 70.0, f"Citation validity ({cit_validity}%) below 70% threshold: {verification.get('unsupported_claims')}"
    assert len(verification.get("unsupported_claims", [])) == 0, f"Citations failed to resolve to retrieved chunks: {verification.get('unsupported_claims')}"

    # 3. Document chunks cited in final answer
    import re
    assert re.search(r"\[(?:FIA|doc|Document|art|article)", data["final_answer"], re.IGNORECASE), "No document chunks cited in final answer"

    # 4. No uncited numbers
    uncited_numbers = verification.get("uncited_factual_claims", [])
    assert len(uncited_numbers) == 0, f"Uncited numbers found in final answer: {uncited_numbers}"

    # 5. Factual content verified
    assert "798" in data["final_answer"] or "mass" in data["final_answer"].lower()
    print("\n>>> REAL END-TO-END FIA PDF RAG TEST PASSED SUCCESSFULLY! <<<")


if __name__ == "__main__":
    test_real_pdf_rag_end_to_end()
